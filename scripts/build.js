// Dependency-free build for this project's named-import ES modules.
// Classic bundles also work when the HTML is opened directly via file://.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

for (const entry of ['patterns']) {
  const visited = new Set();
  const parts = [];
  async function visit(url) {
    if (visited.has(url.href)) return;
    visited.add(url.href);
    const source = await readFile(url, 'utf8');
    const imports = /^\s*import\s+\{[^}]+\}\s+from\s+['"](.+)['"];?\s*$/gm;
    for (const match of source.matchAll(imports)) {
      await visit(new URL(match[1], url));
    }
    const body = source.replace(imports, '').replace(/^export\s+(?=function|const|let)/gm, '');
    if (/^\s*(import|export)\s/m.test(body)) throw new Error(`Unsupported module syntax: ${url}`);
    parts.push(body);
  }
  await visit(new URL(`./${entry}.js`, import.meta.url));
  await writeFile(new URL(`./${entry}.bundle.js`, import.meta.url),
    `// Generated by npm run build. Edit the source modules instead.\n(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`);
}

// Render the calculator component in the single workspace.
const panel = await readFile(new URL('../components/calculator.html', import.meta.url), 'utf8');
for (const page of ['patterns']) {
  const url = new URL(`../${page}.html`, import.meta.url);
  let html = await readFile(url, 'utf8');
  html = html.replace(/<!-- calculator:start -->[\s\S]*?<!-- calculator:end -->/,
    `<!-- calculator:start -->\n${panel}<!-- calculator:end -->`);
  // New file contents get new URLs, so browsers cannot reuse stale CSS/JS.
  const assets = /(?:href|src)="((?:styles|scripts)\/[^"?]+)(?:\?[^\"]*)?"/g;
  for (const match of [...html.matchAll(assets)]) {
    const contents = await readFile(new URL(`../${match[1]}`, import.meta.url));
    const version = createHash('sha256').update(contents).digest('hex').slice(0, 12);
    html = html.replace(match[0], match[0].split('=')[0] + `="${match[1]}?v=${version}"`);
  }
  await writeFile(url, html);
}
